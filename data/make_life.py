#!/usr/bin/env python3
"""Builds life-data.js for Compare Paths from:
  data/mit.json         MIT Living Wage Calculator (updated Feb 15, 2026), metro pages: title, 1-adult wages,
                        typical salaries by occupational area (fetched Nov 10, 2026)
  data/mit-family.json  the same metro pages, all 12 household columns: wages and yearly costs by category
Run from the repo root: python3 data/make_life.py"""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
one = json.load(open(ROOT / 'data' / 'mit.json'))
fam = json.load(open(ROOT / 'data' / 'mit-family.json'))
def money_list(s):
    out, cur = [], ''
    # strings like "$4,047,$0,$3,075" : split on '$'
    return [float(x.strip(',').replace(',', '')) for x in s.split('$') if x.strip(',')]
ORDER = ['19740', '14500', '17820', '22660', '24300', '38060', '19100', '12420', '16980', '42660', '34980', '41620']
SHORT = {'19740': 'Denver', '14500': 'Boulder', '17820': 'Colorado Springs', '22660': 'Fort Collins', '24300': 'Grand Junction',
         '38060': 'Phoenix', '19100': 'Dallas–Fort Worth', '12420': 'Austin', '16980': 'Chicago', '42660': 'Seattle',
         '34980': 'Nashville', '41620': 'Salt Lake City'}
OCC = ['Management', 'Business and financial', 'Computer and math', 'Architecture and engineering', 'Life, physical and social science',
       'Community and social service', 'Legal', 'Education', 'Arts, design and media', 'Healthcare practitioners', 'Healthcare support',
       'Protective service', 'Food preparation and serving', 'Building and grounds', 'Personal care', 'Sales', 'Office and administrative',
       'Farming, fishing and forestry', 'Construction', 'Installation and repair', 'Production', 'Transportation']
CATS = ['Food', 'Child care', 'Health care', 'Housing', 'Transportation', 'Civic', 'Internet and phone', 'Other']
metros = []
for k in ORDER:
    o, f = one[k], fam[k]
    j = money_list(o['j'])
    assert len(j) == 22, (k, len(j))
    metros.append({'id': k, 'n': SHORT[k], 't': o['t'], 'st': o['t'].split(', ')[-1][:2],
                   'lw': f['w'][0], 'minw': f['w'][2][0], 'c': f['c'][:8], 'after': f['c'][8], 'tax': f['c'][9], 'pre': f['c'][10],
                   'j': [int(v) for v in j]})
js = ('/* Life after college data for Compare Paths. Generated by data/make_life.py; do not edit by hand.\n'
      '   MIT Living Wage Calculator (Glasmeier, livingwage.mit.edu), metro areas, updated February 15, 2026.\n'
      '   Columns: 1 adult with 0-3 children; 2 adults (1 working) with 0-3; 2 adults (both working) with 0-3.\n'
      '   c rows: ' + ', '.join(CATS) + ' (yearly dollars). j: typical yearly salary by occupational area (BLS, via MIT). */\n'
      'window.PFC_LIFE_DATA = ' + json.dumps({'cats': CATS, 'occ': OCC, 'metros': metros}, separators=(',', ':')) + ';\n')
(ROOT / 'life-data.js').write_text(js)
print('wrote life-data.js', len(js), 'bytes')
# cross-check: 1-adult columns in both pulls agree
for k in ORDER:
    c1 = money_list(one[k]['c'])
    assert [round(x) for x in c1[:8]] == [round(r[0]) for r in fam[k]['c'][:8]], k
print('1-adult costs match between pulls')
